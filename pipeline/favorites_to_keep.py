#!/usr/bin/env python3
"""Turn a Reverso favorites CSV into pipeline/keep_lemmas.txt.

For every single-word favorite, find the kaikki (Wiktionary) lemmas the word maps to, either as the
headword, in a lemma's inflection table or through a form-of sense, and list them so build.py keeps
them even when Tatoeba has no example for them. Lemmas already in the bundle are harmless duplicates;
this also keeps the *other* lemmas of a found word (so "ingorgo" keeps "ingorgare" for Did-you-mean).

    .venv/Scripts/python -I favorites_to_keep.py "C:/path/Favorites.csv" [out/bundle.json]
"""
import csv
import importlib.util
import json
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("build", os.path.join(ROOT, "build.py"))
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)

WORD = re.compile(r"[^\W\d_]+")


def main():
    csv_path = sys.argv[1]
    bundle_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "out", "bundle.json")
    with open(csv_path, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    words = sorted({build.norm_form(r["source"]) for r in rows if WORD.fullmatch(r["source"].strip())})
    print(f"{len(rows)} rows, {len(words)} distinct single words")

    in_bundle = set()
    if os.path.exists(bundle_path):
        with open(bundle_path, encoding="utf-8") as f:
            in_bundle = {x["form"] for x in json.load(f)["forms"]}

    entries, form_of = build.parse_kaikki(os.path.join(ROOT, "raw", "kaikki-italian.jsonl"))
    wanted = set(words)
    cand = defaultdict(set)            # favorite word -> {lemma word}
    by_word = defaultdict(set)
    for (w, pos) in entries:
        by_word[w].add(pos)
    for (w, pos), ent in entries.items():
        for form in wanted & set(ent["forms"]):
            sets = [frozenset(t.split()) for t in ent["forms"][form] if t]
            if not build.best_tags(sets)[0]:
                cand[form].add(w)
    for inflected, lemma_ws, pos, tags in form_of:
        if inflected in wanted:
            for lw in lemma_ws:
                if lw in by_word and not (tags and set(tags.split()) & build.RARE_TAGS):
                    cand[inflected].add(lw)

    keep, unresolved = {}, []
    for w in words:
        found = cand.get(w, set())
        if not found:
            unresolved.append(w)
            continue
        for lw in found:
            keep.setdefault(lw, w)
    out = os.path.join(ROOT, "keep_lemmas.txt")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Lemmas kept by build.py even without Tatoeba examples (one per line, # comments).\n")
        f.write("# Generated by favorites_to_keep.py from a Reverso favorites export; edit freely.\n")
        for lw in sorted(keep):
            f.write(f"{lw}\n")
    missing = [w for w in words if w not in in_bundle]
    print(f"{len(keep)} lemmas -> {out}")
    print(f"{len(missing)} favorites not in current bundle, resolved: "
          f"{len([w for w in missing if w not in unresolved])}")
    print("unresolved:", unresolved)


if __name__ == "__main__":
    main()
